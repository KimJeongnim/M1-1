import pandas as pd


# ========================================
# 데이터 불러오기
# ========================================

df = pd.read_csv("data/지역별_관광현황_2023_2025.csv")

# 기준년월에서 연도와 월 추출
df["연도"] = df["기준년월"].astype(str).str[:4].astype(int)
df["월"] = df["기준년월"].astype(str).str[4:6].astype(int)

print("===== EDA 시작 =====")


# ========================================
# 1. 지역별 평균 관광객 수
# ========================================

print("\n===== 1. 지역별 평균 관광객 수 =====")

region_avg = (
    df.groupby("지역")["방문자수"]
    .mean()
    .sort_values(ascending=False)
)

print(region_avg)


# ========================================
# 2. 지역별 총 관광객 수
# ========================================

print("\n===== 2. 지역별 총 관광객 수 =====")

region_sum = (
    df.groupby("지역")["방문자수"]
    .sum()
    .sort_values(ascending=False)
)

print(region_sum)


# ========================================
# 3. 연도별 전체 관광객 수
# ========================================

print("\n===== 3. 연도별 전체 관광객 수 =====")

year_sum = (
    df.groupby("연도")["방문자수"]
    .sum()
)

print(year_sum)


# ========================================
# 4. 월별 평균 관광객 수
# ========================================

print("\n===== 4. 월별 평균 관광객 수 =====")

month_avg = (
    df.groupby("월")["방문자수"]
    .mean()
)

print(month_avg)


# ========================================
# 5. 방문자수가 가장 높은 경우
# ========================================

print("\n===== 5. 방문자수가 가장 높은 경우 =====")

max_row = df.loc[df["방문자수"].idxmax()]

print(max_row)


# ========================================
# 6. 방문자수가 가장 낮은 경우
# ========================================

print("\n===== 6. 방문자수가 가장 낮은 경우 =====")

min_row = df.loc[df["방문자수"].idxmin()]

print(min_row)


# ========================================
# 7. 가장 높은 방문자수 증감률
# ========================================

print("\n===== 7. 가장 높은 방문자수 증감률 =====")

max_growth = df.loc[df["방문자수증감률"].idxmax()]

print(max_growth)


# ========================================
# 8. 가장 낮은 방문자수 증감률
# ========================================

print("\n===== 8. 가장 낮은 방문자수 증감률 =====")

min_growth = df.loc[df["방문자수증감률"].idxmin()]

print(min_growth)


# ========================================
# 9. 연도별 × 월별 평균 방문자 수
# ========================================

print("\n===== 9. 연도별 × 월별 평균 방문자 수 =====")

year_month_avg = (
    df.groupby(["연도", "월"])["방문자수"]
    .mean()
    .unstack()
)

print(year_month_avg.to_string())


# ========================================
# 10. 지역별 × 연도별 평균 방문자 수
# ========================================

print("\n===== 10. 지역별 × 연도별 평균 방문자 수 =====")

region_year_avg = (
    df.groupby(["지역", "연도"])["방문자수"]
    .mean()
    .unstack()
)

print(region_year_avg.to_string())


# ========================================
# 11. 지역별 2023 → 2025 변화율
# ========================================

print("\n===== 11. 지역별 2023 → 2025 변화율 =====")

region_year = (
    df.groupby(["지역", "연도"])["방문자수"]
    .mean()
    .unstack()
)

region_change = (
    (region_year[2025] - region_year[2023])
    / region_year[2023]
    * 100
).sort_values(ascending=False)

print(region_change)


# ========================================
# 12. 지역별 연도별 변화율
# ========================================

print("\n===== 12. 지역별 연도별 변화율 =====")

region_year_change = region_year.pct_change(axis=1) * 100

print(region_year_change.to_string())


# ========================================
# 13. 급등 구간 분석
# ========================================

print("\n===== 13. 방문자수 증감률 TOP 10 =====")

top_increase = df.nlargest(
    10,
    "방문자수증감률"
)[
    ["기준년월", "지역", "방문자수", "방문자수증감률"]
]

print(top_increase.to_string(index=False))


# ========================================
# 14. 급락 구간 분석
# ========================================

print("\n===== 14. 방문자수 증감률 하위 10 =====")

top_decrease = df.nsmallest(
    10,
    "방문자수증감률"
)[
    ["기준년월", "지역", "방문자수", "방문자수증감률"]
]

print(top_decrease.to_string(index=False))


# ========================================
# 15. 주요 분석 결과 요약
# ========================================

print("\n===== 15. 주요 분석 결과 요약 =====")


# ----------------------------------------
# 15-1. 연도별 전체 방문자 수 변화율
# ----------------------------------------

print("\n[연도별 전체 방문자 수 변화율]")

for year in [2024, 2025]:

    previous_year = year - 1

    change = (
        (year_sum[year] - year_sum[previous_year])
        / year_sum[previous_year]
        * 100
    )

    print(
        f"{previous_year} → {year}: "
        f"{change:.2f}%"
    )


# ----------------------------------------
# 15-2. 월별 평균 방문자 수 최고/최저
# ----------------------------------------

print("\n[월별 평균 방문자 수]")

max_month = month_avg.idxmax()
min_month = month_avg.idxmin()

print(
    f"가장 높은 월: {max_month}월 "
    f"({month_avg[max_month]:,.0f}명)"
)

print(
    f"가장 낮은 월: {min_month}월 "
    f"({month_avg[min_month]:,.0f}명)"
)


# ----------------------------------------
# 15-3. 2023 → 2025 성장률 최고/최저 지역
# ----------------------------------------

print("\n[2023 → 2025 지역별 변화율]")

max_region = region_change.idxmax()
min_region = region_change.idxmin()

print(
    f"가장 많이 증가한 지역: "
    f"{max_region} "
    f"({region_change[max_region]:.2f}%)"
)

print(
    f"가장 많이 감소한 지역: "
    f"{min_region} "
    f"({region_change[min_region]:.2f}%)"
)


# ----------------------------------------
# 15-4. 증감률 최대/최소 지역 및 시점
# ----------------------------------------

print("\n[증감률 극단값]")

max_change_row = df.loc[
    df["방문자수증감률"].idxmax()
]

min_change_row = df.loc[
    df["방문자수증감률"].idxmin()
]

print(
    f"최대 증가: "
    f"{max_change_row['기준년월']} "
    f"{max_change_row['지역']} "
    f"({max_change_row['방문자수증감률']:.1f}%)"
)

print(
    f"최대 감소: "
    f"{min_change_row['기준년월']} "
    f"{min_change_row['지역']} "
    f"({min_change_row['방문자수증감률']:.1f}%)"
)


# ----------------------------------------
# 15-5. 전체 데이터 기본 정보
# ----------------------------------------

print("\n[데이터 기본 정보]")

print(f"전체 데이터 수: {len(df):,}개")
print(f"지역 수: {df['지역'].nunique()}개")
print(
    f"분석 기간: "
    f"{df['기준년월'].min()} ~ "
    f"{df['기준년월'].max()}"
)


# ========================================
# EDA 종료
# ========================================

print("\n===== EDA 완료 =====")